//! §333 的**预算**在本层留下的那一个形状：[`BudgetView`]。
//!
//! 设计 `docs/superpowers/specs/2026-10-05-p3d-model-registry-router-design.md` §6.1。
//!
//! # 投影由驱动做，不由语义层做
//!
//! **语义层产出它自己的 `Budget`（§333 的分配对象）**，那是它本来就有的东西；
//! **驱动把它投影成 [`BudgetView`]** 传进 `RoutingRequest`。驱动本来就同时依赖两侧
//! （它装配迁移、组装 `RoutingRequest`），故这条投影不新增任何边——
//! **`语义层 → 资源层` 这条反向边在任何时刻都不出现**。本层的 `BudgetView`
//! 因此**不需要任何一方来「实现」它**，只需要驱动构造它。
//!
//! # 本层不为 `BudgetView` 建记账
//!
//! **预扣 / 结算 / 父子分配 / 判「预计超预算」（§110 的 Budget Validator）全归语义层**，
//! 设计的 §6.2 逐条列出。本模块只有这一个类型声明，**没有**任何加减、比较、换算或校验的函数。
//!
//! # 为什么不是一个 trait
//!
//! 共享面要求「把这个视图写成一个待实现的接口」，本设计的兑现方式是**一个类型、加一个构造方**
//! （驱动），不是一个 trait：**不定义 trait 是刻意的**——一个没有实现者的 trait 是**假接口**，
//! 而本仓对「声明了没有产生方的东西」一贯的处置是删或写明理由（设计 §6.1）。
//! 若语义层落地后确实需要多态，那时再抽 trait，并同时补照片。

/// §333 Budget 的**只读投影**：该任务当前可用的剩余额度。
///
/// 五个字段**照录 §333**（`docs/spec/05-normative.md:2502-2516`）：
/// `money` / `wall_time` / `token` / `gpu_time` / `network_transfer`。
///
/// **单位与取值域规范未定义**（§333 只给字段名）。本层**不解释、不换算、不记账**：
/// 它只把这个投影交给排序策略。`None` = 该量纲当前**不构成约束**；
/// `Some(0)` = **额度为零**——两者不是同一件事，混同会让「不约束」变成
/// 「一分钱都不能花」。本类型在这两者之间不做任何折合。
///
/// **字段是 `pub` 的，没有需要靠私有性守的不变量**：它是一份纯数据投影，
/// 由驱动直接构造（见模块头的「为什么不是一个 trait」）。故本类型**不派生任何东西**，
/// 也**不提供构造闸门**：没有当场消费方的派生（`Debug` / `PartialEq` 等）在这里一律不加。
pub struct BudgetView {
    pub money: Option<i64>,
    pub wall_time: Option<i64>,
    pub token: Option<i64>,
    pub gpu_time: Option<i64>,
    pub network_transfer: Option<i64>,
}
