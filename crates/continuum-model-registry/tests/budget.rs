//! Task 9：§333 的只读预算投影 [`BudgetView`] 的**编译期**用例。
//!
//! # 本文件没有一个运行期断言，也不该有
//!
//! `BudgetView` 是一个**纯数据投影**（字段 `pub`、无方法、无判定、无派生），
//! **从构造到读回之间没有一行本 crate 的代码**。故任何「读回来还是原值吗」的运行期断言都**必然恒真**：
//! 它验的是 `Option<i64>` 自己的字段读取语义，**不是本 crate 的任何东西**，
//! 任何不导致编译错误的实现改动都改不动它。设计 §10 第 2 条据此明写：本阶段**不为它写运行期用例，
//! 只钉类型与签名**（`docs/superpowers/specs/2026-10-05-p3d-model-registry-router-design.md:1218-1220`）。
//! 本文件先前写过十条 `assert_ne!` 与数条 `assert_eq!`，**已删**——不是「用例没用」，
//! 是**恒真的断言不构成证据**（错误做法的来历留在本句）。
//!
//! # 照片形态：编译通过 / 编译不过
//!
//! `tests/` 是**独立的 crate**。它能用**结构体字面量**构造出 [`BudgetView`]，就证明了
//! **字段是 `pub`、没有强制闸门**——实测实证是「去掉任一维的 `pub` 即 `E0616`」。
//! 下方两个 `const _` 把 §333 的五个量纲一次穷举钉住：
//!
//! - **名字**：字面量里逐项写出；改一个名字即编译不过（`E0560` / `E0609`）；
//! - **类型**：字面量里逐项带 `i64` 后缀（理由见下），改类型即 `E0308`；
//! - **个数**：**恰好五个**——少一个即 `E0560`，多一个即 `E0063`。
//!
//! **`i64` 后缀是承重的，不是风格**：写成 `Some(11)` 时整数字面量会**随字段类型推断**，
//! 于是把 `Option<i64>` 改成 `Option<u32>` 也照样编译——那就**不是**「钉住了类型」。
//! 带上 `i64` 后缀，这类改动才会在编译期红。
//!
//! **订正（错误说法的来历留在原地）**：本文件先前写「（有闸门就只能经闸门构造）」——**那句是错的**。
//! 一个显式闸门（如 `try_new`）**不拦**结构体字面量；字面量构造不过去，唯一的原因是**字段私有**。
//! 故字面量能构造**证不出**「本层不另设构造便利函数」，只证得出**字段是 `pub`**；先前那句不再作判据。
//!
//! # 本条判据守不住的那一半
//!
//! `None`（该量纲当前**不构成约束**）与 `Some(0)`（**额度为零**）**不得混同**——本 crate
//! 只保证**装得下**这个区别，**不保证没人把它抹掉**：折叠发生在**驱动侧的投影**里（设计 §6.1：
//! 投影由驱动做），本 crate 里**没有可施加该变异的实现体**。守卫点在**投影方与消费方**
//! （计划 `## 遗留` 的「`BudgetView` 的 `None` ≠ `Some(0)` 谁守」一条；收件人：驱动侧的投影实现与子项目 G）。
//! **本文件不为它写断言**——本 crate 里没有那个折叠的落点，写了也恒真。

use continuum_model_registry::BudgetView;

/// §333 的五个量纲：**名字 / 类型 / 个数**一次穷举钉住。**判据是编译通过，不是任何 `assert`。**
///
/// 逐项 `Some(<值>i64)`：`i64` 后缀钉**类型**，`.0` 的值本身不承载判据（故不比较、不读回）。
const _: BudgetView = BudgetView {
    money: Some(11i64),
    wall_time: Some(22i64),
    token: Some(33i64),
    gpu_time: Some(44i64),
    network_transfer: Some(55i64),
};

/// 另一侧：五个量纲都**装得下** `None`（该量纲当前不构成约束）。
///
/// 这一条比上面那条**弱**，据实说明：`None` 在内层类型上是多态的（`Option<i64>` 与 `Option<u32>`
/// 都装得下它），故它只钉「字段是某种 `Option`」，**不钉内层是 `i64`**——后者由上面那个
/// 带 `i64` 后缀的 `const` 钉。它单独仍有用：任一维若被改成非 `Option` 类型，本行即 `E0308`。
const _: BudgetView = BudgetView {
    money: None,
    wall_time: None,
    token: None,
    gpu_time: None,
    network_transfer: None,
};
