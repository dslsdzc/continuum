// 本设计按 §17／§18 的「档位与推理强度分离」读成「Tier1 ＋ 低推理强度」，
// **不给 `EscalationStep` 加第六个成员**：加一个不在阶梯里的成员会让「照录 §251」这句话变假
// （设计 §7.1、§11 第 21 条）。
//
// # 它为什么需要一份**编译失败**样例，而不是运行期用例
//
// 「写不出来」是**签名层**命题：运行期用例无论怎么写，都只能证明「我没写过这个标识符」，
// 证明不了「写不出来」。故用 trybuild 的编译失败样例，把失败钉在**预期的报错**（E0599）上
// ——否则「因为拼错文件名而编译失败」也会让用例变绿。
//
// # 为什么本样例只写这一处错
//
// 实测（rustc 1.95）把两处错写进同一个函数体时，rustc 只报第一条，第二条根本不出现
// ——合并会让没被报出来的那一条**没有照片**（同 `tests/router.rs` 文档里的那条判据）。
